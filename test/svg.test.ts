describe("optimizeSVG", () => {
	it("actually runs SVGO on realistic dvisvgm output", () => {
		// preset-default strips comments; if the comment survives, SVGO was
		// bypassed and every other assertion here would be vacuous.
		expect(optimizeSVG(DVISVGM_SVG, "p-")).not.toContain("generated by dvisvgm");
	});

	it("keeps the viewBox so the diagram still scales", () => {
		const out = optimizeSVG(DVISVGM_SVG, "p-");
		expect(out).toContain("viewBox");
	});

	it("keeps ids (cleanupIds disabled) and keeps them prefixed", () => {
		const out = optimizeSVG(DVISVGM_SVG, "p-");
		expect(out).toContain("p-g0-120");
	});

	it("does not throw on the currentColor the dark-mode adaption introduces", () => {
		const adapted = adaptColorsForDarkMode(DVISVGM_SVG);
		expect(() => optimizeSVG(adapted, "p-")).not.toThrow();
		const out = optimizeSVG(adapted, "p-");
		expect(out).toContain("svg");
	});

	it("preserves the adapted colours through a real SVGO pass", () => {
		// If SVGO dropped the adapted colours (by collapsing the wrapper group,
		// say), dark mode would silently break for every diagram.
		const out = optimizeSVG(adaptColorsForDarkMode(DVISVGM_SVG), "p-");
		expect(out).not.toContain("generated by dvisvgm");
		expect(out).toContain("currentColor");
		// The white fill was moved onto the dark page colour and survived.
		expect(out).toMatch(/fill="#1e1e1e"/);
		expect(out).not.toMatch(/#fff/i);
	});

	it("rejects, rather than passes through, an SVG that cannot be parsed", () => {
		// The SVG is untrusted: if it cannot be parsed it cannot be vetted.
		const broken = "<svg><g fill='#000'</svg>";
		expect(() => optimizeSVG(broken, "p-")).toThrow(SvgRejectedError);
	});

	it("rejects the unquoted-slash handler that slips past the regex sanitiser", () => {
		const evasive = `<svg xmlns='http://www.w3.org/2000/svg'><image href="x"/onerror="alert(1)"/></svg>`;
		expect(() => optimizeSVG(evasive, "p-")).toThrow(SvgRejectedError);
	});

	it("drops elements outside the allowlist: style, a, animate, set", () => {
		const hostile =
			`<svg xmlns='http://www.w3.org/2000/svg'>` +
			`<style>@import url(https://example.com/x.css);</style>` +
			`<a href='https://example.com'><rect width='9' height='9'/></a>` +
			`<animate attributeName='href' to='javascript:alert(1)'/>` +
			`<rect id='keep' width='9' height='9'/></svg>`;
		const out = optimizeSVG(hostile, "p-");
		expect(out).not.toMatch(/<style|<a[ >]|<animate|@import|example\.com/);
		expect(out).toContain("p-keep");
	});

	it("drops handlers, external hrefs and external url() references", () => {
		const hostile =
			`<svg xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink'>` +
			`<rect width='9' height='9' onclick='alert(1)' fill='url(https://example.com/p)'/>` +
			`<use xlink:href='https://example.com/sprite.svg#a'/>` +
			`<use href='javascript&#58;alert(1)'/>` +
			`<path d='M0 0h9' fill='red'/></svg>`;
		const out = optimizeSVG(hostile, "p-");
		expect(out).not.toMatch(/onclick|example\.com|javascript/i);
		expect(out).toContain("<path");
	});

	it("keeps local references and inline raster images", () => {
		const data = "data:image/png;base64,iVBORw0KGgo=";
		const svg =
			`<svg xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink'>` +
			`<defs><path id='g0-1' d='M0 0h9'/></defs><use xlink:href='#g0-1'/>` +
			`<image width='4' height='4' xlink:href='${data}'/></svg>`;
		const out = optimizeSVG(svg, "p-");
		expect(out).toContain('href="#p-g0-1"');
		expect(out).toContain(data);
	});

	it("rejects a non-image data: href", () => {
		const svg =
			`<svg xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink'>` +
			`<image xlink:href='data:image/svg+xml;base64,PHN2Zy8+'/><rect width='1' height='1'/></svg>`;
		expect(optimizeSVG(svg, "p-")).not.toContain("svg+xml");
	});
});

describe("prepareSvgForDisplay", () => {
	it("adapts colours only in adaptive mode AND only on a dark theme", () => {
		expect(prepareSvgForDisplay(DVISVGM_SVG, "p-", "adaptive", true)).toContain("currentColor");
		expect(prepareSvgForDisplay(DVISVGM_SVG, "p-", "adaptive", false)).not.toContain("currentColor");
	});

	it("leaves colours untouched in light-canvas and off modes, dark theme or not", () => {
		// light-canvas gets its readability from the light panel in styles.css,
		// so the colours themselves must stay exactly as TeX drew them.
		for (const mode of ["light-canvas", "off"] as const) {
			const dark = prepareSvgForDisplay(DVISVGM_SVG, "p-", mode, true);
			expect(dark).not.toContain("currentColor");
			expect(dark).toContain("#000");
			expect(dark).toContain("#fff");
		}
	});

	it("defaults to leaving colours alone", () => {
		expect(prepareSvgForDisplay(DVISVGM_SVG, "p-")).not.toContain("currentColor");
	});

	it("always sanitises, even when adaptation is off", () => {
		const hostile = `<svg><script>alert(1)</script><g fill='#000'/></svg>`;
		expect(prepareSvgForDisplay(hostile, "p-", "off", true)).not.toContain("script");
	});

	it("gives the viewer's copy ids disjoint from the inline copy's", () => {
		// Both copies are in the document while the viewer is open; a shared id
		// would let one diagram's <use> resolve to the other's glyph.
		const ids = (svg: string): string[] =>
			[...svg.matchAll(/\bid=["']([^"']+)["']/g)].map((match) => match[1] ?? "");
		const inline = ids(prepareSvgForDisplay(DVISVGM_SVG, "tikz-abcd1234-"));
		const viewer = ids(prepareSvgForDisplay(DVISVGM_SVG, "tikz-zoom-abcd1234-"));
		expect(inline.length).toBeGreaterThan(0);
		expect(viewer.length).toBe(inline.length);
		expect(viewer.filter((id) => inline.includes(id))).toEqual([]);
	});

	it("keeps the viewBox and absolute dimensions the viewer sizes from", () => {
		// SVGO may rewrite `pt` to unitless px; either is an absolute length,
		// which `SVGLength.value` converts without layout. A percentage is not.
		const out = prepareSvgForDisplay(DVISVGM_SVG, "p-");
		expect(out).toMatch(/viewBox="-43\.4 -44\.3 33\.4 8\.2"/);
		expect(out).toMatch(/width="[\d.]+(pt)?"/);
		expect(out).toMatch(/height="[\d.]+(pt)?"/);
	});
});

/** Deepest `<g>` nesting in serialised SVG. */
function groupDepth(svg: string): number {
	let depth = 0;
	let max = 0;
	for (const match of svg.matchAll(/<(\/?)g\b[^>]*?(\/?)>/g)) {
		if (match[1]) depth--;
		else if (!match[2]) max = Math.max(max, ++depth);
	}
	return max;
}

/**
 * The shape pgfplots `surf` produces through pgfsys-dvisvgm.def: per facet,
 * colour and opacity groups that are never closed, each holding the facet
 * *and* the next facet's groups, so SVGO's collapseGroups cannot touch them.
 */
function surfChain(facets: number): string {
	let open = "";
	for (let i = 0; i < facets; i++) {
		const hex = (i % 256).toString(16).padStart(2, "0");
		open +=
			`<g fill='#0000${hex}' stroke='#0000${hex}'><g stroke-opacity='0.9'><g fill-opacity='0.9'>` +
			`<g stroke='#0000cc'><path d='M${i} 0L${i + 1} 0L${i} 1Z'/>`;
	}
	return (
		`<svg version='1.1' xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink' viewBox='0 0 100 100'>` +
		`<g clip-path='url(#c)'>${open}${"</g>".repeat(facets * 4)}</g>` +
		`<clipPath id='c'><path d='M0 0H100V100Z'/></clipPath></svg>`
	);
}

describe("flattening runaway group nesting", () => {
	it("brings a 3,000-deep surf chain down to a few levels, quickly", () => {
		const deep = surfChain(750);
		expect(groupDepth(deep)).toBe(3001);
		const started = Date.now();
		const out = optimizeSVG(deep, "p-");
		expect(Date.now() - started).toBeLessThan(3000);
		expect(groupDepth(out)).toBeLessThanOrEqual(3);
		expect(out.match(/<path\b/g)?.length).toBe(751); // 750 facets + the clip path
	});

	it("keeps paint order and hands each facet exactly its inherited paint", () => {
		const out = optimizeSVG(surfChain(40), "p-");
		// SVGO hoists what every facet shares onto the clip group: the inner
		// group's stroke (which wins over the outer one, as inheritance would
		// have it) and both opacities.
		expect(out).toMatch(/<g fill-opacity="\.9" stroke="#00c" stroke-opacity="\.9" clip-path="url\(#p-c\)">/);
		const facets = [...out.matchAll(/<path\b[^>]*>/g)].map((match) => match[0]).slice(0, 40);
		for (const [i, tag] of facets.entries()) {
			expect(tag).toContain(`d="M${i} 0`);
			// Facet 0's `#000000` is SVG's default fill, which SVGO drops.
			// (SVGO also shortens `#000011` to `#001`, hence the parse.)
			if (i > 0) expect(parseHexColor(/fill="(#[0-9a-f]+)"/.exec(tag)?.[1] ?? "")).toEqual({ r: 0, g: 0, b: i });
		}
	});

	it("never dissolves a group whose meaning is not just inherited paint", () => {
		// opacity and clip-path composite the group as a whole; transform, id,
		// class and style change geometry, references or the cascade.
		const keepers: Record<string, string>[] = [
			{ opacity: "0.5" }, { "clip-path": "url(#c)" }, { mask: "url(#m)" }, { filter: "url(#f)" },
			{ transform: "translate(1 1)" }, { id: "keep" }, { class: "x" }, { style: "fill:red" },
		];
		for (const attributes of keepers) {
			const root = tree(group({ fill: "#f00" }, group({ ...attributes, stroke: "#00f" }, leaf({}))));
			flattenPresentationGroups(root);
			// The pure-paint wrapper is gone, its fill handed to the keeper.
			expect(root.children).toHaveLength(1);
			const kept = root.children[0] as XastElement;
			expect(kept.name).toBe("g");
			expect(kept.attributes).toEqual({ ...attributes, stroke: "#00f", fill: "#f00" });
			expect(kept.children).toHaveLength(1);
		}
	});

	it("lets a child's own attribute win, and leaves defs and clip paths alone", () => {
		const clip = element("clipPath", { id: "c" }, group({ fill: "#0f0" }, leaf({})));
		const root = tree(group({ fill: "#f00", stroke: "#00f" }, leaf({ fill: "none" }), leaf({}), clip));
		flattenPresentationGroups(root);
		const [own, inherited, clipPath] = root.children as XastElement[];
		expect(own.attributes).toEqual({ fill: "none", stroke: "#00f" });
		expect(inherited.attributes).toEqual({ fill: "#f00", stroke: "#00f" });
		expect(clipPath.name).toBe("clipPath");
		expect((clipPath.children[0] as XastElement).name).toBe("g"); // untouched inside
	});

	it("measures depth without recursion", () => {
		let node = leaf({});
		for (let i = 0; i < 20_000; i++) node = group({}, node);
		expect(maxGroupDepth(tree(node))).toBe(20_000);
	});

	it("leaves diagrams at or below the threshold to SVGO alone", () => {
		// Below the threshold nothing is restructured, so every diagram that
		// rendered before renders byte-for-byte the same.
		const chain = (depth: number): string => {
			let svg = "";
			for (let i = 0; i < depth; i++) svg += `<g fill='#00${i % 10}'><path d='M${i} 0L1 1'/>`;
			return `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 9 9'>${svg}${"</g>".repeat(depth)}</svg>`;
		};
		expect(groupDepth(optimizeSVG(chain(FLATTEN_DEPTH_THRESHOLD), "p-"))).toBeGreaterThan(FLATTEN_DEPTH_THRESHOLD / 2);
		expect(groupDepth(optimizeSVG(chain(FLATTEN_DEPTH_THRESHOLD + 1), "p-"))).toBeLessThanOrEqual(1);
	});
});
